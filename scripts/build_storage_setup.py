"""Compose a one-shot repair for verified 001-only installations; never connect to a DB."""
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MIGRATIONS = ("002_ai_feedback.sql", "003_nlp_learning.sql", "004_learning_storage_access.sql")
PREFLIGHT = """-- Generated by scripts/build_storage_setup.py from the canonical migrations below.
-- For an existing FluentFive database with migration 001 only.
-- Paste the ENTIRE file into Supabase SQL Editor and Run once.
-- Preserves existing content/history; never drops tables or disables RLS.
begin;

do $$
declare missing text; installed text; installed_count int;
begin
  select string_agg(t, ', ' order by t) into missing
  from unnest(array['profiles','activities','sessions','chunks','writings',
    'quiz_questions','test_results','daily_stats','sentences','passages']) as tables(t)
  where to_regclass('public.' || t) is null;
  if missing is not null then
    raise exception 'Base FluentFive tables missing: %. Apply migration 001 first.', missing;
  end if;

  select string_agg(t, ', ' order by t),count(*) into installed,installed_count
  from unnest(array['ai_analyses','api_usage','flashcard_reviews',
    'nlp_analyses','practice_sessions']) as tables(t)
  where to_regclass('public.' || t) is not null;
  if installed_count = 5 then
    raise exception 'NLP tables already exist. Do not rerun this installer; use migration 004 for access repair.';
  elsif installed_count > 0 then
    raise exception 'NLP setup is partially installed: %. Use the individual migrations after inspecting the schema.', installed;
  end if;
end; $$;
"""


def build() -> str:
    parts = [PREFLIGHT.rstrip()]
    for name in MIGRATIONS:
        source = (ROOT / "supabase" / "migrations" / name).read_text()
        # Remove only the outer transaction wrappers. PL/pgSQL BEGIN has no semicolon.
        lines = [line.rstrip() for line in source.splitlines() if line.strip().lower() not in {"begin;", "commit;"}]
        digest = hashlib.sha256(source.encode()).hexdigest()
        parts.append(f"-- Source: {name}; sha256: {digest}\n" + "\n".join(lines).strip())
    parts.append("commit;\n")
    return "\n\n".join(parts)


if __name__ == "__main__":
    output = ROOT / "supabase" / "repairs" / "install_missing_nlp.sql"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(build())
    print(f"Prepared {output.relative_to(ROOT)} ({len(output.read_text().splitlines())} lines). No database was accessed.")
